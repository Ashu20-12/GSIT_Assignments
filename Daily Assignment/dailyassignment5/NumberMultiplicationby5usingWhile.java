package dailyassignment5;

public class NumberMultiplicationby5usingWhile {

	public static void main(String[] args) {
		 int n = 5;
	     int i = 1;

	     while (i <= n) {
	    	 System.out.println(i + " → " + 5*i);    // Math.pow returns a double value so converting it explicitly to int .
	         i++;
	     }

	}

}
